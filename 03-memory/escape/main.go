package main

import "fmt"

// ============================================================
// 逃逸分析深度解析
// ============================================================
//
// 【面试高频问题】
// 1. 什么是逃逸分析？
// 2. 什么时候变量会逃逸到堆上？
// 3. 如何查看逃逸分析结果？
// 4. 为什么逃逸到堆上会影响性能？
// 5. 如何避免不必要的逃逸？
//
// 查看逃逸分析: go build -gcflags="-m" ./03-memory/escape/
// 更详细:       go build -gcflags="-m -m" ./03-memory/escape/

// ----------------------------------------------------------
// 逃逸分析规则
// ----------------------------------------------------------
// 编译器通过分析变量的生命周期和使用方式，决定分配在栈还是堆。
//
// 栈分配:
//   - 函数返回后不再被引用
//   - 编译期能确定大小
//   - 分配/释放几乎零成本（移动栈指针）
//   - 对 GC 无压力
//
// 堆分配:
//   - 函数返回后仍被引用（逃逸）
//   - 大小在编译期不确定（如 make([]T, n) 中 n 是变量）
//   - 需要 GC 回收，有额外开销
//   - 分配需要找空闲内存，可能触发 GC

func main() {
	escapeByReturn()
	escapeByInterface()
	escapeByClosure()
	escapeBySlice()
	escapeByPointer()
	noEscape()
}

// ----------------------------------------------------------
// 1. 返回局部变量指针 → 逃逸
// ----------------------------------------------------------
// 变量在函数返回后仍被引用，必须逃逸到堆上。

func escapeByReturn() *int {
	// x 逃逸到堆上: "moved to heap: x"
	x := 42
	return &x
}

// ----------------------------------------------------------
// 2. 赋值给接口 → 逃逸
// ----------------------------------------------------------
// 接口是动态类型，编译器不知道具体类型，所以值会逃逸。

func escapeByInterface() interface{} {
	// x 逃逸到堆上: "x does not escape" 不，实际上:
	// 如果用空接口包装，值会逃逸
	x := 42
	return x // 值类型赋给 interface 会装箱（逃逸到堆）
}

// ----------------------------------------------------------
// 3. 闭包引用 → 逃逸
// ----------------------------------------------------------
// 闭包捕获的变量如果在外部使用，会逃逸。

func escapeByClosure() func() int {
	// x 逃逸到堆上: 闭包捕获，生命周期超出函数
	x := 42
	return func() int {
		return x
	}
}

// ----------------------------------------------------------
// 4. 动态大小的 slice/map → 逃逸
// ----------------------------------------------------------
func escapeBySlice() {
	// 编译期大小确定 → 栈
	// 如果是常量或小的固定大小
	_ = [4]int{1, 2, 3, 4} // 栈上分配

	// 以下情况逃逸到堆:
	// 1. 大小是变量
	n := 10
	_ = make([]int, n) // "make([]int, n) escapes to heap"

	// 2. append 可能触发扩容
	s := make([]int, 0)
	s = append(s, 1) // 如果 append 后被外部引用，s 可能逃逸
	_ = s

	// 3. 返回 slice
	fmt.Println()
}

// ----------------------------------------------------------
// 5. 指针参数导致的逃逸
// ----------------------------------------------------------
func escapeByPointer() {
	// 如果函数接受指针参数，且不能内联，
	// 编译器保守地认为指针可能逃逸

	x := 42
	escapeSink(&x) // x 可能逃逸（取决于 escapeSink 是否能内联）
	_ = x
}

//go:noinline
func escapeSink(p *int) {
	_ = p
}

// ----------------------------------------------------------
// 6. 不逃逸的情况
// ----------------------------------------------------------
func noEscape() {
	// 局部变量，函数返回后不再使用 → 栈
	x := 42
	y := x + 1
	_ = y

	// 固定大小数组 → 栈
	arr := [100]int{}
	_ = arr

	// 值传递的 struct → 栈
	type Point struct{ X, Y int }
	p := Point{1, 2}
	q := p // 值复制，不逃逸
	_ = q

	// 切片字面量（小且不逃逸）
	s := []int{1, 2, 3}
	_ = s

	fmt.Println("以上变量都分配在栈上（不逃逸）")
}

// ----------------------------------------------------------
// 面试要点总结
// ----------------------------------------------------------
//
// 查看逃逸分析:
//   go build -gcflags="-m"         # 基本分析
//   go build -gcflags="-m -m"      # 更详细
//   go build -gcflags="-m -l -l"   # 禁止内联后分析（更保守）
//
// 常见逃逸场景:
//   1. 返回局部变量指针        → 逃逸
//   2. 赋值给 interface        → 逃逸
//   3. 闭包捕获变量            → 逃逸
//   4. send 到 channel 的值    → 逃逸
//   5. 在 slice/map 中存储指针 → 值逃逸
//   6. reflect 使用            → 逃逸
//   7. fmt.Printf 等可变参数   → 逃逸
//
// 避免逃逸的技巧:
//   1. 值传递代替指针（小结构体）
//   2. 预分配 slice 容量
//   3. 避免 fmt.Sprintf（用 strconv）
//   4. 使用具体类型代替 interface（热路径）
//   5. 使用 sync.Pool 复用对象
//   6. 给编译器更多内联机会（小函数）
//
// 逃逸的性能影响:
//   栈分配: ~1ns（移动 SP）
//   堆分配: ~50-100ns（mallocgc + GC 开销）
//   如果每秒分配百万次，差异巨大

func init() {
	fmt.Println("=== 逃逸分析要点 ===")
	fmt.Println("查看: go build -gcflags=\"-m\" ./03-memory/escape/")
	fmt.Println()
}
